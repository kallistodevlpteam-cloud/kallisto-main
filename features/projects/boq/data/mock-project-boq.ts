const CREATED_AT = "2026-07-26T09:30:00.000Z";

function createItem(input: {
  id: string;
  sectionId: string;
  subsectionId?: string | null;
  code: string;
  description: string;
  unit: string;
  quantity?: number | null;
  rate?: number | null;
  status?: BoqItemStatus;
  notes?: string;
}): BoqItem {
  const amount = calculateBoqAmount(input.quantity, input.rate);

  return {
    ...input,
    subsectionId: input.subsectionId ?? null,
    amount,
    status:
      amount === null ? "Needs attention" : input.status ?? "Reviewed",
    lastUpdatedAt: CREATED_AT,
    lastUpdatedBy: "Arjun Mehta",
  };
}


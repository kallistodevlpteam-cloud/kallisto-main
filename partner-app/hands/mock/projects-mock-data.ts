export function calculateHandsProjectsMetrics(projects: HandsProjectRecord[]): HandsProjectSummaryMetrics {
  const activeProjects = projects.filter((p) => p.status === "active").length;
  const upcomingProjects = projects.filter((p) => p.status === "upcoming").length;
  const completedProjects = projects.filter((p) => p.status === "completed").length;

  return {
    activeProjects: activeProjects || 8,
    upcomingProjects: upcomingProjects || 6,
    completedProjects: completedProjects || 2,
    overallProgress: "92%",
  };
}

export function getHandsProjectById(idOrSlug: string): HandsProjectRecord {
  const normalized = idOrSlug.toLowerCase().trim();
  const found = INITIAL_HANDS_PROJECTS.find(
    (p) => p.id.toLowerCase() === normalized || p.slug.toLowerCase() === normalized
  );
  return found || INITIAL_HANDS_PROJECTS[0];
}
